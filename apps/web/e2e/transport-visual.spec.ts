import { expect, test } from "@playwright/test";

test("el mapa renderiza rutas, paraderos y cuatro buses que se mueven", async ({ page }) => {
  const consoleErrors:string[]=[];
  const failedTiles:string[]=[];
  let successfulTiles=0;
  page.on("console",message=>{if(message.type()==="error")consoleErrors.push(message.text())});
  page.on("requestfailed",request=>{if(request.url().includes("tile.openstreetmap.org"))failedTiles.push(request.url())});
  page.on("response",response=>{if(response.url().includes("tile.openstreetmap.org")&&response.ok())successfulTiles++});
  await page.goto("/transporte");
  const map=page.locator(".transport-map");
  await expect(map).toHaveAttribute("data-map-status","ready",{timeout:20_000});
  const canvas=map.locator("canvas.maplibregl-canvas");
  await expect(canvas).toBeVisible();
  const box=await canvas.boundingBox();
  expect(box?.width).toBeGreaterThan(300);
  expect(box?.height).toBeGreaterThan(400);
  await expect.poll(()=>successfulTiles,{timeout:15_000}).toBeGreaterThan(0);
  await expect(page.locator(".map-panel")).toHaveAttribute("data-routes-rendered","3");
  await expect(page.locator(".route-option")).toHaveCount(3);
  await expect(page.locator(".bus-marker")).toHaveCount(4);
  const moving=page.locator('[data-vehicle-id="DEMO-BUS-1"]');
  const start=await moving.boundingBox();
  await page.waitForTimeout(4000);
  const advanced=await moving.boundingBox();
  expect(Math.abs((advanced?.x??0)-(start?.x??0))+Math.abs((advanced?.y??0)-(start?.y??0))).toBeGreaterThan(0.05);
  await page.getByRole("button",{name:"Pausar simulación"}).click();
  await expect(page.getByText("Simulación pausada")).toBeVisible();
  await page.waitForTimeout(1100);
  const paused=await moving.boundingBox();
  await page.waitForTimeout(1700);
  const still=await moving.boundingBox();
  expect(Math.abs((still?.x??0)-(paused?.x??0))+Math.abs((still?.y??0)-(paused?.y??0))).toBeLessThan(0.25);
  await page.getByRole("button",{name:"Reanudar simulación"}).click();
  await page.getByRole("button",{name:"5×"}).click();
  await expect(page.getByRole("button",{name:"5×"})).toHaveClass(/selected/);
  const secondRoute=page.locator(".route-option").nth(1);
  await secondRoute.click();
  await expect(secondRoute).toHaveClass(/active/);
  await page.screenshot({path:"artifacts/playwright/transport-acceptance.png",fullPage:true});
  expect(failedTiles).toEqual([]);
  expect(consoleErrors).toEqual([]);
});
